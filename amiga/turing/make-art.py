#!/usr/bin/env python3
"""Editable pixel-art master for the native TuringStats Workbench icon."""
from pathlib import Path
from PIL import Image, ImageDraw
root = Path(__file__).resolve().parent
out = root.parent.parent / '.context/amiga/turing-1023'
out.mkdir(parents=True, exist_ok=True)
palette = [(0,0,0),(14,22,35),(42,57,76),(77,177,255),(255,165,0),
           (238,246,255),(105,127,151),(21,38,55),(9,16,26)]
im = Image.new('P',(64,64),0)
im.putpalette(sum((list(c) for c in palette),[])+[0]*(768-3*len(palette)))
d = ImageDraw.Draw(im)
# Stand and USB cable sit behind the portrait LCD enclosure.
d.line([(43,43),(55,43),(55,53),(59,53)],fill=6,width=2)
d.rectangle((57,49,61,56),fill=2);d.rectangle((58,47,60,49),fill=5)
d.rectangle((26,49,34,57),fill=2);d.line((27,49,27,56),fill=6)
d.rounded_rectangle((17,56,44,60),radius=2,fill=1)
d.line((20,56,40,56),fill=6)
# Soft-edged case, blue trim, dark screen.
d.rounded_rectangle((7,2,49,52),radius=5,fill=1)
d.rounded_rectangle((8,3,48,51),radius=4,outline=6,width=1)
d.line((12,4,43,4),fill=5)
d.rectangle((11,7,45,45),fill=8)
d.rectangle((12,8,44,10),fill=3)
# Tiny CPU caption and status line.
glyphs={'C':['111','100','100','100','111'],'P':['110','101','110','100','100'],'U':['101','101','101','101','111']}
x=15
for ch in 'CPU':
 for y,row in enumerate(glyphs[ch]):
  for j,v in enumerate(row):
   if v=='1':d.point((x+j,14+y),fill=5)
 x+=4
d.rectangle((31,14,40,15),fill=4);d.rectangle((31,18,37,19),fill=6)
# Orange and blue activity bars.
for x,h,col in [(15,8,3),(21,13,3),(27,10,4),(33,17,4),(39,14,3)]:
 d.rectangle((x,40-h,x+3,40),fill=col)
d.line((14,42,43,42),fill=6)
d.rectangle((25,47,31,48),fill=3);d.point((42,48),fill=4)
indices=list(im.tobytes());planes=[0]*(2*64*4)
for y in range(64):
 for x in range(64):
  v=indices[y*64+x];r,g,b=palette[v];classic=0 if not v else 1 if r+g+b<360 else 2
  for bit in range(2):
   if classic&(1<<bit):planes[bit*256+y*4+x//16]|=1<<(15-x%16)
padded=palette+[(0,0,0)]*(128-len(palette))
text='/* Generated by make-art.py; edit the pixel-art master, not this file. */\n#define ICON_COLOR 1\n'
text+='static UWORD icon_planes[]={'+','.join(map(str,planes))+'};\n'
text+='static UBYTE icon_pixels[]={'+','.join(map(str,indices))+'};\n'
text+='static struct ColorRegister icon_palette[]={'+','.join('{'+','.join(map(str,c))+'}' for c in padded)+'};\n'
(root/'icon-art.h').write_text(text)
im.save(out/'turing-icon.png',transparency=0)
preview=Image.new('RGB',(256,256),(58,64,74))
rgba=im.convert('RGBA');rgba.putalpha(Image.frombytes('L',(64,64),bytes(255 if n else 0 for n in indices)))
rgba=rgba.resize((256,256),Image.Resampling.NEAREST);preview.paste(rgba,(0,0),rgba)
preview.save(out/'turing-icon-preview.png')
